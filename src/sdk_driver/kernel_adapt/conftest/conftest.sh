# Generate kernel API capability macros by compiling probes with the target
# kernel's Kbuild environment.  This script is intended to run before any
# sdk_driver kernel module is compiled.

set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
TABLE_FILE="${SCRIPT_DIR}/check_functions/check_tables.csv"
PROBE_DIR="${SCRIPT_DIR}/probes"
OUTPUT_FILE=
KERNEL_SRC=
ARCH_ARG=
CROSS_COMPILE_ARG=
KEEP_WORK=0

log()
{
    printf '[CONFTEST] [INFO]  %s\n' "$*" >&2
}

log_warn()
{
    printf '[CONFTEST] [WARN]  %s\n' "$*" >&2
}

log_err()
{
    printf '[CONFTEST] [ERROR] %s\n' "$*" >&2
}

usage()
{
    cat <<EOF
Usage: $0 --kernel-src PATH [options]

Options:
  --output FILE           Generated header (required)
  --table FILE            Probe table CSV
  --arch ARCH             Target kernel ARCH passed to make
  --cross-compile PREFIX  CROSS_COMPILE prefix passed to make
  --keep-work             Keep the temporary probe directory
  -h, --help              Show this help
EOF
}

while [ "$#" -gt 0 ]; do
    case "$1" in
        -k|--kernel-src)
            [ "$#" -ge 2 ] || { log_err "Missing value for $1"; exit 2; }
            KERNEL_SRC=$2
            shift 2
            ;;
        --output)
            [ "$#" -ge 2 ] || { log_err "Missing value for $1"; exit 2; }
            OUTPUT_FILE=$2
            shift 2
            ;;
        --table)
            [ "$#" -ge 2 ] || { log_err "Missing value for $1"; exit 2; }
            TABLE_FILE=$2
            shift 2
            ;;
        --arch)
            [ "$#" -ge 2 ] || { log_err "Missing value for $1"; exit 2; }
            ARCH_ARG=$2
            shift 2
            ;;
        --cross-compile)
            [ "$#" -ge 2 ] || { log_err "Missing value for $1"; exit 2; }
            CROSS_COMPILE_ARG=$2
            shift 2
            ;;
        --keep-work)
            KEEP_WORK=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            log_err "Unknown option: $1"
            usage >&2
            exit 2
            ;;
    esac
done

[ -n "$KERNEL_SRC" ] || { log_err "--kernel-src is required"; exit 2; }
[ -d "$KERNEL_SRC" ] || { log_err "Kernel build tree not found: $KERNEL_SRC"; exit 1; }
[ -n "$OUTPUT_FILE" ] || { log_err "--output is required"; exit 2; }
[ -f "$TABLE_FILE" ] || { log_err "Probe table not found: $TABLE_FILE"; exit 1; }

WORK_DIR=$(mktemp -d "${TMPDIR:-/tmp}/ascend-conftest.XXXXXX")
# Older Kbuild releases (including Linux 3.10) expect this external-module
# bookkeeping directory to exist before compiling the first object.
mkdir -p "$WORK_DIR/.tmp_versions"
cleanup()
{
    if [ "$KEEP_WORK" -eq 1 ]; then
        log "Conftest work directory: $WORK_DIR"
    else
        rm -rf "$WORK_DIR"
    fi
}
trap cleanup EXIT HUP INT TERM

RESULT_FILE="$WORK_DIR/conftest.h"
LOG_FILE="$WORK_DIR/conftest.log"
OUTPUT_LOG="${OUTPUT_FILE}.log"
mkdir -p "$(dirname -- "$OUTPUT_FILE")"

CONFTEST_KCFLAGS="${KCFLAGS:-} -Wno-missing-declarations -Wno-missing-prototypes -Werror=incompatible-pointer-types -Werror=implicit-function-declaration"
CONFTEST_CC=${CC:-${CROSS_COMPILE_ARG}gcc}
CONFTEST_CC_NAME=$($CONFTEST_CC --version 2>/dev/null | sed -n '1p' || true)
case "$CONFTEST_CC_NAME" in
    *gcc*|*GCC*)
        CONFTEST_GCC_VERSION=$($CONFTEST_CC -dumpfullversion -dumpversion 2>/dev/null || true)
        CONFTEST_GCC_MAJOR=${CONFTEST_GCC_VERSION%%.*}
        case "$CONFTEST_GCC_MAJOR" in
            ''|*[!0-9]*) ;;
            *)
                if [ "$CONFTEST_GCC_MAJOR" -ge 5 ]; then
                    CONFTEST_KCFLAGS="$CONFTEST_KCFLAGS -Werror=int-conversion"
                fi
                ;;
        esac
        ;;
esac

# Linux 3.x Kbuild predates toolchain defaults that emit PIE objects.  A PIE
# object is invalid for the kernel code model, so disable it for old trees.
KERNEL_VERSION_TEXT=$(make -s -C "$KERNEL_SRC" kernelversion 2>/dev/null || true)
case "$KERNEL_VERSION_TEXT" in
    3.*) CONFTEST_KCFLAGS="$CONFTEST_KCFLAGS -fno-pie" ;;
esac

cat > "$RESULT_FILE" <<'EOF'
/*
 * Auto-generated by kernel_adapt/conftest/conftest.sh.
 * Do not edit. Regenerate this file for every target kernel build tree.
 */
#ifndef ASCEND_KERNEL_CONFTEST_H
#define ASCEND_KERNEL_CONFTEST_H

EOF

compile_current_probe()
{
    set -- -s -C "$KERNEL_SRC" "M=$WORK_DIR" "KCFLAGS=$CONFTEST_KCFLAGS"
    [ -z "$ARCH_ARG" ] || set -- "$@" "ARCH=$ARCH_ARG"
    [ -z "$CROSS_COMPILE_ARG" ] || set -- "$@" "CROSS_COMPILE=$CROSS_COMPILE_ARG"
    make "$@" conftest_probe.o >>"$LOG_FILE" 2>&1
}

cat > "$WORK_DIR/conftest_probe.c" <<'EOF'
#include <linux/module.h>
void conftest_kbuild_sanity(void) { }
EOF
cat > "$WORK_DIR/Makefile" <<'EOF'
obj-m := conftest_probe.o
EOF
if ! compile_current_probe; then
    cp "$LOG_FILE" "$OUTPUT_LOG"
    log_err "Kernel probe sanity build failed; see: $OUTPUT_LOG"
    exit 1
fi

run_probe()
{
    probe_name=$1
    macro_name=$2
    category=$3
    source_file="${PROBE_DIR}/${category}/${probe_name}.c"

    if [ ! -f "$source_file" ]; then
        log_err "Probe source not found: $source_file"
        return 1
    fi

    cp "$source_file" "$WORK_DIR/conftest_probe.c"
    cat > "$WORK_DIR/Makefile" <<'EOF'
obj-m := conftest_probe.o
EOF
    rm -f "$WORK_DIR/conftest_probe.o" "$WORK_DIR/.conftest_probe.o.cmd"

    if compile_current_probe; then
        echo "#define $macro_name" >> "$RESULT_FILE"
        printf '  %-52s yes\n' "$macro_name"
    else
        echo "#undef $macro_name" >> "$RESULT_FILE"
        printf '  %-52s no\n' "$macro_name"
    fi
}

log "Generating kernel conftest header from: $KERNEL_SRC"
while IFS=, read -r probe_name macro_name category extra; do
    probe_name=$(printf '%s' "$probe_name" | tr -d ' "\r')
    macro_name=$(printf '%s' "$macro_name" | tr -d ' "\r')
    category=$(printf '%s' "$category" | tr -d ' "\r')
    [ "$probe_name" = "file_name" ] && continue
    [ -n "$probe_name" ] || continue
    run_probe "$probe_name" "$macro_name" "$category"
done < "$TABLE_FILE"

cat >> "$RESULT_FILE" <<'EOF'

#endif /* ASCEND_KERNEL_CONFTEST_H */
EOF

TMP_OUTPUT="${OUTPUT_FILE}.tmp.$$"
cp "$RESULT_FILE" "$TMP_OUTPUT"
mv "$TMP_OUTPUT" "$OUTPUT_FILE"
cp "$LOG_FILE" "$OUTPUT_LOG"
log "Generated: $OUTPUT_FILE"
log "Probe log: $OUTPUT_LOG"
printf '\n===== BEGIN conftest.h: %s =====\n' "$OUTPUT_FILE"
cat "$OUTPUT_FILE"
printf '===== END conftest.h: %s =====\n' "$OUTPUT_FILE"
